import PDFDocument from "pdfkit";
import { formatMoney } from "./money";
import { trackingIdFor } from "./orders";
import type { SerializedOrder } from "./types";

/** A6 thermal-style shipping label, branded per business. */
export function generateShippingLabel(
  order: SerializedOrder,
  businessName = "ShopFlow",
  currency = "INR",
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A6", margin: 0 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const W = doc.page.width;
    const H = doc.page.height;
    const M = 22;
    const C = { ink: "#111111", muted: "#555555", brand: "#0F7A4D", line: "#222222" };

    doc.rect(0, 0, W, 54).fill(C.ink);
    doc
      .fill("#FFFFFF")
      .font("Helvetica-Bold")
      .fontSize(13)
      .text(businessName.toUpperCase().slice(0, 22), M, 18);
    doc.font("Helvetica").fontSize(7).fill("#9BE3B5").text("EXPRESS PARCEL", M, 36);
    doc
      .font("Helvetica-Bold")
      .fontSize(10)
      .fill("#FFFFFF")
      .text(`#${String(order.id).padStart(5, "0")}`, W - M - 90, 22, {
        width: 90,
        align: "right",
      });

    let y = 70;
    doc.fill(C.muted).font("Helvetica").fontSize(7).text("SHIP TO", M, y);
    y += 11;
    doc
      .fill(C.ink)
      .font("Helvetica-Bold")
      .fontSize(12)
      .text(order.userName ?? "Customer", M, y, { width: W - M * 2 });
    y += 16;
    doc
      .font("Helvetica")
      .fontSize(9)
      .text(order.userAddress ?? "Address confirmed in chat", M, y, { width: W - M * 2 });
    y = doc.y + 4;
    doc.fontSize(8).fill(C.muted).text(`Phone: +${order.userPhone}`, M, y);

    y += 18;
    doc.moveTo(M, y).lineTo(W - M, y).dash(3, { space: 2 }).lineWidth(0.7).stroke(C.line).undash();

    y += 10;
    doc.fill(C.muted).font("Helvetica").fontSize(7).text("CONTENTS", M, y);
    y += 11;
    for (const it of order.items.slice(0, 6)) {
      doc
        .fill(C.ink)
        .font("Helvetica")
        .fontSize(9)
        .text(`${it.qty} x  ${it.name}`.slice(0, 40), M, y, { width: W - M * 2 });
      doc
        .font("Helvetica-Bold")
        .fontSize(9)
        .text(formatMoney(it.price * it.qty, currency), M, y, {
          width: W - M * 2,
          align: "right",
        });
      y += 14;
    }

    y += 4;
    doc.moveTo(M, y).lineTo(W - M, y).lineWidth(1.2).stroke(C.line);
    y += 9;
    doc.fill(C.ink).font("Helvetica-Bold").fontSize(11).text("TOTAL", M, y);
    doc.text(formatMoney(order.totalAmount, currency), M, y, {
      width: W - M * 2,
      align: "right",
    });

    y += 22;
    doc
      .fill(C.muted)
      .font("Helvetica")
      .fontSize(7.5)
      .text(
        `STATUS: ${order.status}   CHANNEL: ${order.channel.toUpperCase()}   ${new Date(
          order.createdAt,
        )
          .toISOString()
          .slice(0, 10)}`,
        M,
        y,
      );

    const tracking = trackingIdFor(order.id);
    const barcodeY = H - 86;
    const barcodeH = 44;
    let x = M;
    const seed = order.id * 2654435761;
    doc.rect(M - 4, barcodeY - 6, W - M * 2 + 8, barcodeH + 30).lineWidth(0.7).stroke("#BBBBBB");
    while (x < W - M - 2) {
      const w = ((seed + x * 31) % 4) + 1;
      const gap = ((seed + x * 17) % 3) + 1.5;
      if (x + w > W - M - 2) break;
      doc.rect(x, barcodeY, w, barcodeH).fill(C.ink);
      x += w + gap;
    }
    doc
      .font("Helvetica")
      .fontSize(8)
      .fill(C.ink)
      .text(tracking, M, barcodeY + barcodeH + 5, { width: W - M * 2, align: "center" });

    doc
      .font("Helvetica")
      .fontSize(6.5)
      .fill(C.brand)
      .text(`Generated by ShopFlow AI for ${businessName}`, M, H - 24, {
        width: W - M * 2,
        align: "center",
      });

    doc.end();
  });
}
